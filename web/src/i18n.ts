export type TranslationKey = keyof typeof english;
const copy: Record<Language, Record<TranslationKey, string>> = { en: english, zh: chinese };

export function translate(language: Language, key: TranslationKey, values: Record<string, string | number> = {}): string {
  return copy[language][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match);
}
